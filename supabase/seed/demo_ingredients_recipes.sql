do $$
declare missing text;
begin
  select string_agg(distinct r.product_name || ' / ' || r.ingredient_name, ', ') into missing
  from demo_recipe r
  where not exists (select 1 from public.products p where p.product_name = r.product_name)
     or not exists (select 1 from public.ingredients i where lower(i.ingredient_name) = lower(r.ingredient_name));
  if missing is not null then raise exception 'DEMO RECIPES ABORTED: unknown product or ingredient: %', missing; end if;
end $$;

insert into public.product_ingredients (product_id, ingredient_id, quantity_needed)
select p.product_id, i.ingredient_id, r.quantity
from demo_recipe r
join public.products p on p.product_name = r.product_name
join public.ingredients i on lower(i.ingredient_name) = lower(r.ingredient_name)
on conflict (product_id, ingredient_id) do nothing;

do $$
declare missing text;
begin
  select string_agg(p.product_name, ', ') into missing from public.products p
  where not exists (select 1 from public.product_ingredients pi where pi.product_id = p.product_id);
  if missing is not null then raise exception 'DEMO RECIPES ABORTED: products without a recipe: %', missing; end if;
end $$;

